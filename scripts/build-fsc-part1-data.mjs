/**
 * Reads public/documents/scholarship-results/fsc-part-1-test-result.xlsx
 * and writes lib/scholarship-fsc-part1-data.ts
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import XLSX from 'xlsx'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const xlsxPath = path.join(root, 'public/documents/scholarship-results/fsc-part-1-test-result.xlsx')
const outPath = path.join(root, 'lib/scholarship-fsc-part1-data.ts')

function cell(v) {
  if (v == null || v === '') return ''
  if (typeof v === 'number' && v % 1 !== 0) return String(v)
  if (typeof v === 'number') return String(v)
  return String(v).trim()
}

const STD_HDR = ['S.no', 'Name', 'Father Name', 'Total Percentage', 'Remarks']

function isSectionTitle(row) {
  const a = String(row[0] ?? '').trim()
  return a === 'CS- Group' || a === 'PRE-MEDICAL & PRE-ENGINEERING'
}

function looksLikeHeaderRow(row) {
  return String(row[0] ?? '').trim().toLowerCase() === 's.no'
}

function looksLikeDataRow(row) {
  const f = row[0]
  return typeof f === 'number' || /^\d+$/.test(String(f))
}

function parseGroups(data) {
  const groups = []
  let i = 0
  while (i < data.length) {
    const row = data[i]
    if (!isSectionTitle(row)) {
      i++
      continue
    }
    const sec = String(row[0]).trim()
    i++
    let hdr = STD_HDR
    if (i < data.length && looksLikeHeaderRow(data[i])) {
      hdr = data[i].map((c) => cell(c))
      i++
    }
    const rows = []
    while (i < data.length) {
      const r = data[i]
      if (isSectionTitle(r)) break
      if (!looksLikeDataRow(r)) break
      rows.push(hdr.map((_, ci) => cell(r[ci])))
      i++
    }
    const title =
      sec === 'CS- Group'
        ? 'Ist Year CS- Group'
        : 'Ist Year PRE-MEDICAL & PRE-ENGINEERING'
    groups.push({ title, headers: hdr, rows })
  }
  return groups
}

function escapeStr(s) {
  return JSON.stringify(s)
}

const wb = XLSX.readFile(xlsxPath)
const sheet = wb.Sheets[wb.SheetNames[0]]
const data = XLSX.utils.sheet_to_json(sheet, { header: 1, defval: '' })
const groups = parseGroups(data)

let body = `/**
 * Auto-generated by scripts/build-fsc-part1-data.mjs — do not edit by hand.
 * Source: public/documents/scholarship-results/fsc-part-1-test-result.xlsx
 * Re-run: node scripts/build-fsc-part1-data.mjs
 */

export type FscPart1GroupTable = {
  title: string
  headers: string[]
  rows: string[][]
}

export const FSC_PART1_GROUP_TABLES: FscPart1GroupTable[] = [
`

for (const g of groups) {
  body += `  {\n    title: ${escapeStr(g.title)},\n    headers: ${JSON.stringify(g.headers)},\n    rows: [\n`
  for (const row of g.rows) {
    body += `      ${JSON.stringify(row)},\n`
  }
  body += `    ],\n  },\n`
}

body += `]\n`

fs.writeFileSync(outPath, body, 'utf8')
console.log('Wrote', outPath, `(${groups.length} groups, ${groups.reduce((n, g) => n + g.rows.length, 0)} rows)`)
